"""
End-to-End Pipeline Integration Script (Lead / P1).

Orchestrates teammate modules (when present) via their locked contracts,
runs the procurement simulation to write results/procurement_week.json,
optionally updates docs/procurement_memo.md, and validates all contracts.

Usage:
    python integration/run_pipeline.py --use-dummy --update-memo
    python integration/run_pipeline.py --strict
"""

from __future__ import annotations

import argparse
import importlib
import json
import re
import sys
from pathlib import Path

import pandas as pd

REPO_ROOT = Path(__file__).resolve().parent.parent
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from integration.validate_contracts import validate_all
from procurement.procurement import build_dummy_week_forecast, simulate_week

RESULTS_DIR = REPO_ROOT / "results"
MEMO_PATH = REPO_ROOT / "docs" / "procurement_memo.md"


def _try_run_backtest_if_available() -> None:
    """
    Invoke Features' eval/backtest.py + Modeling's models/fit_predict if present.

    Never reimplements teammate logic; strictly calls locked contracts:
      - eval.backtest.run_backtest(fit_predict, horizon)
      - models.model.fit_predict (or models.quantiles.fit_predict)
    """
    backtest_path = REPO_ROOT / "eval" / "backtest.py"
    clean_path = REPO_ROOT / "data" / "clean_hourly.parquet"
    if not backtest_path.exists() or not clean_path.exists():
        print("[SKIP] Teammate backtest skipped (waiting for data/clean_hourly.parquet or eval/backtest.py).")
        return

    fit_predict = None
    for mod_name in ("models.model", "models.quantiles", "models.train"):
        try:
            mod = importlib.import_module(mod_name)
            if hasattr(mod, "fit_predict"):
                fit_predict = mod.fit_predict
                print(f"[INFO] Found Modeling fit_predict in {mod_name}")
                break
        except ImportError:
            continue

    if fit_predict is None:
        print("[SKIP] Modeling fit_predict not found yet in models/; skipping backtest execution.")
        return

    backtest_mod = importlib.import_module("eval.backtest")
    for horizon in ("day", "week"):
        print(f"[RUN]  eval.backtest.run_backtest(horizon='{horizon}')")
        backtest_mod.run_backtest(fit_predict, horizon)


def update_procurement_memo(result: dict) -> None:
    """Refresh the summary table in docs/procurement_memo.md between marker comments."""
    if not MEMO_PATH.exists():
        return

    mode_label = "DUMMY STUB (pre-H6 wiring)" if result.get("is_dummy_data") else "REAL WALK-FORWARD FORECASTS"
    p90_m = result["cost_breakdown"]["p90_model"]
    p50_m = result["cost_breakdown"]["p50_point"]
    flat_m = result["cost_breakdown"]["flat_p90_avg"]

    table = "\n".join([
        "<!-- PROCUREMENT_SUMMARY_START -->",
        "| Metric | Value | Notes |",
        "| --- | --- | --- |",
        f"| **Data Mode** | `{mode_label}` | Generated by `procurement/procurement.py` |",
        f"| **Sample Week Window** | `{result['week_start']}` to `{result['week_end']}` | {result['n_hours']} hourly intervals |",
        f"| **P90 Risk Exposure (`max(P90 - P50)`)** | **{result['p90_exposure_mw']:,.2f} MW** | Max hourly tail buffer over P50 |",
        f"| **P90 Model Schedule Cost** | **Rs {result['cost_model']:,.2f}** (Rs {result['cost_model']/1e7:,.2f} Cr) | {p90_m['shortfall_hours']} shortfall hrs ({p90_m['shortfall_mwh']:,.1f} MWh) |",
        f"| **Flat Schedule Cost (`mean(P90)`)** | **Rs {result['cost_flat']:,.2f}** (Rs {result['cost_flat']/1e7:,.2f} Cr) | {flat_m['shortfall_hours']} shortfall hrs ({flat_m['shortfall_mwh']:,.1f} MWh) |",
        f"| **Simulated Saving vs. Flat** | **Rs {result['saving']:,.2f}** (Rs {result['saving']/1e7:,.2f} Cr / **{result['saving_pct_vs_flat']}%**) | Identical contracted MWh ({p90_m['contracted_mwh']:,.1f} MWh) |",
        f"| **P50 Point Schedule Cost** | **Rs {result['cost_p50']:,.2f}** (Rs {result['cost_p50']/1e7:,.2f} Cr) | {p50_m['shortfall_hours']} shortfall hrs ({p50_m['shortfall_mwh']:,.1f} MWh) |",
        "<!-- PROCUREMENT_SUMMARY_END -->",
    ])

    text = MEMO_PATH.read_text(encoding="utf-8")
    updated = re.sub(
        r"<!-- PROCUREMENT_SUMMARY_START -->.*?<!-- PROCUREMENT_SUMMARY_END -->",
        table,
        text,
        flags=re.DOTALL,
    )
    MEMO_PATH.write_text(updated, encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description="Run Lead integration pipeline.")
    parser.add_argument(
        "--use-dummy",
        action="store_true",
        help="Allow dummy stub forecast when results/forecasts_week.parquet is not yet present.",
    )
    parser.add_argument(
        "--update-memo",
        action="store_true",
        help="Update docs/procurement_memo.md summary table with simulated numbers.",
    )
    parser.add_argument(
        "--strict",
        action="store_true",
        help="Fail contract validation if any teammate artifact is missing.",
    )
    args = parser.parse_args()

    # Step 1: Attempt teammate backtest if modules & clean data are ready
    _try_run_backtest_if_available()

    # Step 2: Run Lead's procurement simulation on real results or dummy stub
    week_path = RESULTS_DIR / "forecasts_week.parquet"
    day_path = RESULTS_DIR / "forecasts_day.parquet"

    if week_path.exists():
        forecast_df = pd.read_parquet(week_path)
        is_dummy = False
        print(f"[RUN]  Simulating procurement from {week_path.relative_to(REPO_ROOT)}")
    elif day_path.exists():
        forecast_df = pd.read_parquet(day_path)
        is_dummy = False
        print(f"[RUN]  Simulating procurement from {day_path.relative_to(REPO_ROOT)}")
    elif args.use_dummy:
        forecast_df = build_dummy_week_forecast()
        is_dummy = True
        print("[RUN]  Simulating procurement from dummy stub (pre-H6 mode)")
    else:
        print("[ERROR] Neither results/forecasts_week.parquet nor forecasts_day.parquet exists. Pass --use-dummy for stub test.")
        sys.exit(1)

    result = simulate_week(forecast_df, params={})
    result["is_dummy_data"] = is_dummy

    out_path = RESULTS_DIR / "procurement_week.json"
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(json.dumps(result, indent=2), encoding="utf-8")
    print(f"[OK]   Wrote {out_path.relative_to(REPO_ROOT)}")

    if args.update_memo:
        update_procurement_memo(result)
        print(f"[OK]   Updated {MEMO_PATH.relative_to(REPO_ROOT)}")

    # Step 3: Validate contracts
    mode = "strict" if args.strict else "available"
    ok, messages, errors = validate_all(mode=mode)
    print("\n--- Contract Validation ---")
    for m in messages:
        print(m)
    for e in errors:
        print(f"[ERROR]   {e}")

    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()

